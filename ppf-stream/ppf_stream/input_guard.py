#!/usr/bin/env python3
"""Run an input validator, except on a `#ppf-stream` directive.

    input_guard.py <original command ...> -- [validator flags] < test_input

A judge runs `input_validators/` on every `.in` in `data/`.  A directive is one
line naming generated bytes, not the bytes, so no input validator could pass it.
This guard accepts a directive (exit 42) and runs the original validator,
unchanged, on everything else.

Accepting a directive here loses nothing: `convert.py` ran the original
validators on the generated bytes when the directive was written, and the
directive pins those bytes by sha256, which `validate.py` checks before a
submission ever sees them.  The same bytes cannot become invalid later.
"""

import os
import subprocess
import sys
import threading

VALID, JUDGE_ERROR = 42, 1
MARKER = b"#ppf-stream"


def main():
    argv = sys.argv[1:]
    if "--" not in argv:
        print("usage: input_guard.py <command ...> -- [flags]", file=sys.stderr)
        return JUDGE_ERROR
    cut = argv.index("--")
    cmd, flags = argv[:cut], argv[cut + 1:]

    stdin = sys.stdin.buffer
    head = stdin.read(len(MARKER))
    if head == MARKER:
        print("[ppf-stream] directive: generated bytes were validated when it was written",
              file=sys.stderr)
        return VALID

    p = subprocess.Popen([*cmd, *flags], stdin=subprocess.PIPE)

    def feed():
        try:
            p.stdin.write(head)
            while True:
                chunk = stdin.read(1 << 16)
                if not chunk:
                    break
                p.stdin.write(chunk)
            p.stdin.close()
        except BrokenPipeError:        # the validator stopped reading: its verdict stands
            pass

    t = threading.Thread(target=feed, daemon=True)
    t.start()
    rc = p.wait()
    t.join(timeout=1)
    return rc


if __name__ == "__main__":
    sys.exit(main())
