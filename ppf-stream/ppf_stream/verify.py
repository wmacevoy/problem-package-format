#!/usr/bin/env python3
"""Setter-side gate: generate every case, validate it, and judge every submission.

    verify.py <package>

Two checks, both of which exist to catch mistakes at preparation time rather
than at contest time:

  1. Every test case, after the whole `gen | filter | ...` pipeline has run,
     is passed to each program in `input_validators/` on standard input.
     Exit 42 means valid.  This is what catches a filter that produced data
     the problem statement does not allow -- or, far more often, a filter
     that broke the format while doing so.

  2. Every submission is judged, and each must get the verdict its directory
     claims.  A test set that stops rejecting `wrong_answer/` has quietly
     stopped doing its job, which is the usual cost of a late narrowing of
     the constraints.

Note on where input validation happens.  The specification has judge systems
run `input_validators/` against the `.in` files in `data/`, which in a
streaming package are the argument lines, not the data.  So validating the
generated bytes is the setter's job and belongs in a tool like this one.
"""

import importlib.util
import os
import pathlib
import subprocess
import sys
import tempfile

VALID, AC, WA = 42, 42, 43


def load_validate(pkg):
    spec = importlib.util.spec_from_file_location(
        "ppf_validate", pkg / "output_validator" / "validate.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def run_program(path, argv, stdin=None, stdout=None):
    cmd = ([sys.executable, str(path)] if path.suffix == ".py" else [str(path)])
    return subprocess.run(cmd + argv, stdin=stdin, stdout=stdout,
                          stderr=subprocess.PIPE)


def main():
    pkg = pathlib.Path(sys.argv[1]).resolve()
    mod = load_validate(pkg)
    mod.HERE = pkg / "output_validator"

    cases = sorted((pkg / "data").rglob("*.in"))
    validators = [p for p in sorted((pkg / "input_validators").glob("*"))
                  if p.is_file() and p.suffix in (".py", "") and p.stat().st_mode & 0o111]
    # Stands in for `input_validator_args` in the test group configuration.
    argfile = pkg / "input_validators" / "args"
    vargs = argfile.read_text().split() if argfile.exists() else []
    built, bad = {}, 0

    print("input validation")
    for case in cases:
        args = case.read_text().split()
        cache = os.environ.get("PPF_STREAM_CACHE") or str(case.parent)
        try:
            data_path, ans_path, hit = mod.materialize(args, cache)
        except Exception as e:                       # noqa: BLE001
            print(f"  FAIL {case.name:<24} generation failed: {e}")
            bad += 1
            continue
        built[case] = (data_path, ans_path)
        size = data_path.stat().st_size
        verdicts = []
        for v in validators:
            with open(data_path, "rb") as fi:
                r = run_program(v, vargs, stdin=fi, stdout=subprocess.DEVNULL)
            verdicts.append((v.name, r.returncode, r.stderr.decode().strip()))
        ok = all(rc == VALID for _, rc, _ in verdicts)
        bad += not ok
        print(f"  {'OK  ' if ok else 'FAIL'} {case.name:<24} {size:>12,} B"
              f"  [{' '.join(a.split()[0] for a in args)}]")
        for name, rc, err in verdicts:
            if rc != VALID:
                print(f"       {name} exit {rc}: {err.splitlines()[0] if err else ''}")

    print("\nsubmissions")
    for kind, want in (("accepted", AC), ("wrong_answer", WA)):
        d = pkg / "submissions" / kind
        if not d.is_dir():
            continue
        for sol in sorted(p for p in d.iterdir()
                          if p.is_file() and (p.suffix == ".py" or p.stat().st_mode & 0o111)):
            got, diffs = [], []
            for case, (data_path, ans_path) in built.items():
                with tempfile.TemporaryDirectory() as fb:
                    out = pathlib.Path(fb) / "o"
                    with open(data_path, "rb") as fi, open(out, "wb") as fo:
                        run_program(sol, [], stdin=fi, stdout=fo)
                    with open(out, "rb") as fi:
                        r = run_program(pkg / "output_validator" / "judge",
                                        [str(data_path), str(ans_path or out), fb], stdin=fi)
                got.append(r.returncode)
                if r.returncode != AC:
                    diffs.append(case.name)
            ok = all(g == AC for g in got) if want == AC else any(g == WA for g in got)
            bad += not ok
            detail = ("accepted everywhere" if not diffs
                      else "rejected on " + ", ".join(diffs))
            print(f"  {'OK  ' if ok else 'FAIL'} {kind}/{sol.name:<18} {detail}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
